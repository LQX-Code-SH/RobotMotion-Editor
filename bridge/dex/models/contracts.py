"""机型后端显式契约。

协议层只依赖这里的接口，不依赖任何具体机型实现。
BackendBundle 保持可迭代，兼容旧的 `robot, hands, cameras = create_backends(...)` 写法。
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Protocol, runtime_checkable


@runtime_checkable
class RobotBackend(Protocol):
    enabled: bool
    mode: str
    estop: bool

    def enable(self) -> tuple[bool, Any]: ...
    def disable(self) -> bool: ...
    def set_mode(self, mode: str) -> tuple[bool, Any]: ...
    def set_joint_targets(self, targets: dict[str, float]) -> dict: ...
    def start_trajectory(self, trajectory_id: str, frames: list,
                         fps: int = 30, loop: bool = False) -> dict: ...
    def stop(self) -> bool: ...
    def emergency_stop(self) -> None: ...
    def get_joint_states(self) -> dict: ...
    def snapshot_targets(self) -> dict: ...
    def drain_events(self) -> list: ...
    def take_trajectory_done(self) -> str | None: ...
    def trajectory_progress(self) -> dict | None: ...
    def shutdown(self) -> None: ...


@runtime_checkable
class HandsBackend(Protocol):
    def describe(self) -> dict: ...
    def get_state(self) -> dict: ...
    def set_normalized(self, side: str, values: list[float]) -> bool: ...
    def clear_error(self, side: str) -> bool: ...
    def shutdown(self) -> None: ...


@runtime_checkable
class CameraBackend(Protocol):
    available: bool

    def describe(self) -> list: ...
    def info(self, camera: str) -> dict: ...
    def subscribe(self, camera: str, token: int, fps: int, callback) -> tuple[bool, Any]: ...
    def unsubscribe(self, camera: str, token: int) -> None: ...
    def unsubscribe_token(self, token: int) -> None: ...
    def shutdown(self) -> None: ...


@dataclass(frozen=True)
class BackendBundle:
    robot: RobotBackend
    hands: HandsBackend
    cameras: CameraBackend

    def __iter__(self):
        return iter((self.robot, self.hands, self.cameras))

    def __len__(self) -> int:
        return 3

    def __getitem__(self, index: int):
        return (self.robot, self.hands, self.cameras)[index]
